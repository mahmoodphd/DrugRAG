def drug_card(drug_name: str) -> str:
    if not drug_name:
        return "*Pick a drug from the dropdown above.*"
    row = df_main[df_main["drug_name"] == drug_name]
    if row.empty:
        return f"**{drug_name}** not found."
    r = row.iloc[0]

    direction = "anti-angiogenic" if r["net_direction"] < 0 else "pro-angiogenic"
    cluster_meaning = CLUSTER_MAP.get(int(r["cluster"]), f"Cluster {int(r['cluster'])}")
    lit_label, lit_color = LITERATURE_STATUS.get(r["novelty_status"], (r["novelty_status"], "#999"))

    discovery_banner = ""
    if drug_name in CENTERPIECE:
        discovery_banner = (
            "<div style='background:#fff3cd;border-left:4px solid #f4a582;"
            "padding:10px 14px;margin-bottom:12px;border-radius:4px;'>"
            "<b>★ Active-dark discovery candidate</b> — bioactive in our assay, "
            "almost no angiogenesis literature, and confirmed against live PubMed."
            "</div>"
        )

    lit_badge = (
        f"<span style='background:{lit_color};color:white;padding:3px 10px;"
        f"border-radius:4px;font-weight:600;'>{lit_label}</span>"
    )

    card = f"""
{discovery_banner}

## {r['drug_name']}

**Literature status:** {lit_badge} &nbsp;&nbsp; **Rank:** {int(r['rank_final'])} of {len(df_main)}

### Cluster
| | |
|---|---|
| Cluster | {int(r['cluster'])} — {cluster_meaning} |

### Experiment
| metric | value |
|---|---|
| Experimental activity | {r['activity_magnitude']:.2f} |
| Effect direction | {direction} (net = {r['net_direction']:.2f}) |
| Repurposing score | {r['score_v5_final']:.2f} |

### Literature
| metric | value |
|---|---|
| Angiogenesis papers (PubMed) | {int(r['real_angio_pubmed_hits'])} |
| Total PubMed papers | {int(r['real_total_pubmed_hits'])} |
| Literature novelty | {r['novelty_real']:.2f} |
| Papers in our corpus | {int(r['corpus_n_papers'])} |

*How to read these: of all PubMed papers on this drug (**Total**), some mention angiogenesis (**Angiogenesis papers**); of those, a few are in our 6,500-paper corpus (**Papers in our corpus**). The live panel below shows the newest of the angiogenesis papers.*

### Knowledge graph
| metric | value |
|---|---|
| Knowledge-graph links (angiogenesis) | {int(r['angio_edges'])} |
| Mechanistic support (KG) | {r['kg_plausibility']:.2f} |
"""
    return card


def build_drug_explorer():
    """Build the Drug Explorer tab. Returns (dropdown, card_output) for cross-tab use."""
    with gr.Column():
        gr.Markdown("### Drug Explorer\nLook up any of the 1,278 LOPAC drugs.")
        dd = gr.Dropdown(choices=ALL_DRUGS, label="Drug name",
                         filterable=True, allow_custom_value=False)
        card_out = gr.Markdown("*Pick a drug from the dropdown above.*")
        dd.change(fn=drug_card, inputs=dd, outputs=card_out)

        # --- Live PubMed panel (on-demand) ---
        gr.Markdown("---")
        with gr.Row():
            pubmed_btn = gr.Button("🔄 Check latest PubMed", variant="secondary", size="sm")
            pubmed_status = gr.Markdown("")
        pubmed_out = gr.Markdown(
            "*Click the button above to fetch the latest PubMed papers for the selected drug.*"
        )

        def fetch_pubmed_papers(drug_name):
            """On-demand PubMed lookup — lazy imports, short timeout, graceful failure."""
            if not drug_name or not drug_name.strip():
                return "*Select a drug first, then click the button.*"
            try:
                from Bio import Entrez
                import urllib.request
                import xml.etree.ElementTree as ET

                Entrez.email = getattr(__import__("config"), "PUBMED_EMAIL", "") or "user@example.com"
                ncbi_key = getattr(__import__("config"), "NCBI_API_KEY", "")
                if ncbi_key:
                    Entrez.api_key = ncbi_key

                # Build query from the canonical name (matches how the card's counts
                # were computed). Fall back to a stripped drug_name if missing.
                row = df_main[df_main["drug_name"] == drug_name]
                canonical = ""
                if not row.empty and "canonical_name" in row.columns:
                    val = row.iloc[0]["canonical_name"]
                    canonical = str(val).strip() if pd.notna(val) else ""
                if not canonical:
                    canonical = drug_name.split(" ")[0].strip("()[]+-±")
                # Field-restrict BOTH terms to Title/Abstract and phrase-match the drug
                # name, so the live panel returns papers genuinely about this drug AND
                # angiogenesis (avoids PubMed auto-expansion false matches).
                query = (
                    f'"{canonical}"[Title/Abstract] AND '
                    '(angiogenesis[Title/Abstract] OR angiogenic[Title/Abstract] '
                    'OR neovascularization[Title/Abstract] OR "endothelial cell"[Title/Abstract])'
                )
                display_name = canonical

                # Search with a 10-second timeout
                import socket
                old_timeout = socket.getdefaulttimeout()
                socket.setdefaulttimeout(10)
                try:
                    handle = Entrez.esearch(db="pubmed", term=query, retmax=5, sort="date")
                    record = Entrez.read(handle)
                    handle.close()
                    ids = record.get("IdList", [])
                finally:
                    socket.setdefaulttimeout(old_timeout)

                if not ids:
                    return f"No recent PubMed results for *{display_name} + angiogenesis*."

                # Fetch summaries
                socket.setdefaulttimeout(10)
                try:
                    handle = Entrez.esummary(db="pubmed", id=",".join(ids))
                    summaries = Entrez.read(handle)
                    handle.close()
                finally:
                    socket.setdefaulttimeout(old_timeout)

                lines = [
                    f"#### Latest from PubMed (live): recent angiogenesis papers mentioning {display_name}\n"
                ]
                for s in summaries:
                    title = s.get("Title", "(no title)")
                    pmid = s.get("Id", "?")
                    year = s.get("PubDate", "?")[:4]
                    link = f"https://pubmed.ncbi.nlm.nih.gov/{pmid}/"
                    lines.append(f"- **{title}** ({year}) — [PMID {pmid}]({link})")

                lines.append("\n> *These are live PubMed results — distinct from the local corpus used for chat citations.*")
                return "\n".join(lines)

            except Exception as e:
                return (
                    "⚠️ Latest PubMed lookup is unavailable right now.\n\n"
                    f"*(Reason: {type(e).__name__})*\n\n"
                    "> The drug card above is unaffected — it uses local data only."
                )

        pubmed_btn.click(fn=fetch_pubmed_papers, inputs=[dd], outputs=[pubmed_out])
        gr.Markdown(GLOSSARY_MD)
    return dd, card_out


