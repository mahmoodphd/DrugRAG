# Tab 2 — Repurposing Leaderboard
# ════════════════════════════════════════════════════════════════════════════
def build_leaderboard():
    base = df_main.copy()
    base["direction"] = base["net_direction"].apply(lambda x: "anti" if x < 0 else "pro")
    base["literature_status"] = base["novelty_status"].map(
        lambda s: LITERATURE_STATUS.get(s, (s, ""))[0]
    )
    base = base.sort_values("rank_final")

    display_cols_rename = {
        "rank_final": "Rank",
        "drug_name": "Drug",
        "cluster": "Cluster",
        "direction": "Direction",
        "activity_magnitude": "Activity",
        "score_v5_final": "Repurposing score",
        "novelty_real": "Novelty",
        "literature_status": "Literature status",
        "real_angio_pubmed_hits": "Angio papers (PubMed)",
        "corpus_n_papers": "Papers in corpus",
        "angio_edges": "KG links",
        "kg_plausibility": "Mechanistic support (KG)",
    }
    display_df = base[list(display_cols_rename.keys())].rename(columns=display_cols_rename)

    with gr.Column():
        gr.Markdown(
            "### Repurposing Leaderboard\n"
            "All 1,278 drugs ranked by combined score. Click headers to sort."
        )
        with gr.Row():
            dir_filter = gr.Dropdown(
                choices=["All", "anti", "pro"], value="All", label="Effect direction",
            )
            cluster_filter = gr.Dropdown(
                choices=["All"] + [str(i) for i in range(1, 8)],
                value="All", label="Cluster",
            )
            lit_filter = gr.Dropdown(
                choices=["All", "Well-studied", "Some literature",
                         "Missed by corpus", "Genuinely understudied"],
                value="All", label="Literature status",
            )
        table_out = gr.Dataframe(
            value=display_df, interactive=False, wrap=True, max_height=600,
        )

        def filter_table(direction, cluster, lit_status):
            try:
                f = display_df.copy()
                if direction != "All":
                    f = f[f["Direction"] == direction]
                if cluster != "All":
                    f = f[f["Cluster"] == int(cluster)]
                if lit_status != "All":
                    f = f[f["Literature status"] == lit_status]
                return gr.update(value=f)
            except Exception as e:
                print(f"[leaderboard filter] {e}")
                return gr.update(value=display_df)

        for inp in [dir_filter, cluster_filter, lit_filter]:
            inp.change(fn=filter_table, inputs=[dir_filter, cluster_filter, lit_filter],
                       outputs=table_out)
        gr.Markdown(GLOSSARY_MD)


