# Tab 4 — Gap Map (log y, all 8 outliers excluded, landmarks + centerpieces)
# ════════════════════════════════════════════════════════════════════════════
def build_gap_map():
    """Build Gap Map with landmark known anti-angiogenics and clickable points."""
    fig_df = df_main.copy()
    fig_df["direction"] = fig_df["net_direction"].apply(
        lambda x: "anti" if x < 0 else "pro"
    )
    rng = np.random.default_rng(42)
    raw = fig_df["real_angio_pubmed_hits"].astype(float).values
    log_y = np.log10(raw + 1.0)
    jitter = np.where(raw == 0, rng.uniform(-0.18, 0.18, size=len(raw)), 0.0)
    fig_df["log_angio"] = log_y + jitter
    fig_df["angio_papers"] = raw.astype(int)

    # Exclude ALL 8 PubMed false-match outliers (per refsheet.py)
    plotted = fig_df[~fig_df["drug_name"].isin(PUBMED_OUTLIERS)].copy()

    x_med = plotted["activity_magnitude"].median()

    fig = px.scatter(
        plotted,
        x="activity_magnitude", y="log_angio",
        color="direction",
        color_discrete_map={"anti": "#4393c3", "pro": "#d6604d"},
        custom_data=["drug_name"],
        hover_data={
            "drug_name": True, "angio_papers": True, "cluster": True,
            "score_v5_final": ":.2f", "novelty_status": True, "log_angio": False,
        },
        opacity=0.55,
        labels={
            "activity_magnitude": "Experimental activity",
            "log_angio": "Angiogenesis papers (PubMed, log scale)",
            "direction": "Effect direction", "angio_papers": "Angio papers",
        },
    )
    fig.update_traces(marker=dict(size=7, line=dict(width=0.4, color="#444")))

    tick_vals = [0, 1, 2, 3, 4]
    tick_text = ["0", "1", "10", "100", "1,000"]
    fig.update_yaxes(tickvals=tick_vals, ticktext=tick_text)

    # Annotate 3 centerpiece drugs (discovery candidates)
    for name in CENTERPIECE:
        row = plotted[plotted["drug_name"] == name]
        if row.empty:
            continue
        r = row.iloc[0]
        fig.add_annotation(
            x=r["activity_magnitude"], y=r["log_angio"],
            text=f"★ {r['drug_name'].split()[0]}",
            showarrow=True, arrowhead=2, arrowsize=1, arrowwidth=1.2,
            arrowcolor="#222", ax=40, ay=-40,
            font=dict(size=11, color="#222", family="Arial"),
            bgcolor="#fff3cd", bordercolor="#f4a582", borderwidth=1,
        )

    # Annotate 3 landmark known anti-angiogenics (orient a biologist)
    for drug_name, label in LANDMARKS.items():
        row = plotted[plotted["drug_name"] == drug_name]
        if row.empty:
            continue
        r = row.iloc[0]
        fig.add_annotation(
            x=r["activity_magnitude"], y=r["log_angio"],
            text=label,
            showarrow=True, arrowhead=1, arrowsize=0.8, arrowwidth=1,
            arrowcolor="#555", ax=-50, ay=-30,
            font=dict(size=10, color="#333", family="Arial"),
            bgcolor="#e8f4f8", bordercolor="#4393c3", borderwidth=1,
        )

    # Opportunity quadrant shading
    if len(plotted) > 0:
        fig.add_shape(
            type="rect",
            x0=x_med, x1=plotted["activity_magnitude"].max() * 1.02,
            y0=-0.2, y1=1.0,
            line=dict(width=0), fillcolor="rgba(244,165,130,0.12)", layer="below",
        )
        fig.add_annotation(
            x=plotted["activity_magnitude"].max() * 0.99,
            y=0.85, xanchor="right",
            text="<b>Opportunity quadrant</b><br>high activity, few papers",
            showarrow=False, font=dict(size=11, color="#7a4520"), align="right",
        )

    fig.update_layout(
        template="plotly_white", font=dict(size=12), height=600,
        title=dict(text="Activity vs Literature Coverage", x=0.02),
    )

    with gr.Column():
        gr.Markdown("### Literature Gap Map")
        gr.Markdown(
            f"Each dot is a drug. **Click any point to view it in Drug Explorer.** "
            f"Y-axis is on a **log scale**. The shaded **bottom-right is the opportunity "
            f"quadrant** — activity above median ({x_med:.2f}), ≤ 10 angiogenesis papers. "
            f"Blue-labeled landmarks show where *known* anti-angiogenics sit; "
            f"starred drugs are our discovery candidates."
        )
        gap_plot = gr.Plot(value=fig, elem_id="gap_map_plot")
        gr.Markdown(
            f"> **Data-quality caveat.** {len(PUBMED_OUTLIERS)} drugs have PubMed "
            "angiogenesis hits exceeding their total PubMed hits (impossible if genuine), "
            "indicating name false-matches. They are excluded from this scatter and "
            "flagged for the eventual reconciliation pass."
        )
        gr.Markdown(GLOSSARY_MD)
    return gap_plot


