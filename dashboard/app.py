# Tab 7 — Chat (M3) — simplified, mode in Advanced expander
# ════════════════════════════════════════════════════════════════════════════
def build_chat():
    EXAMPLES = [
        "What is the mechanism of Memantine in angiogenesis?",
        "What evidence connects glutamate signaling to endothelial tube formation?",
        "What is known about Adenosine and blood-vessel formation?",
        "Are there any reports linking BNTX to vascular biology?",
    ]

    def run_query(question, mode, progress=gr.Progress(track_tqdm=False)):
        if not question or not question.strip():
            return "*Type a question above and press Run.*", "*Type a question above and press Run.*", ""
        progress(0.1, desc="Initializing LightRAG (first call: ~12 s) …")
        try:
            t_total = time.perf_counter()
            progress(0.3, desc="Retrieving from corpus + LLM call (~40 s) …")
            res = rag_chat.run_both(question, mode=mode)
            elapsed = time.perf_counter() - t_total
    
            rag_md = rag_chat.colorize_citations(res["rag_answer"], res["rag_verdict"])
            plain_md = rag_chat.colorize_citations(res["plain_answer"], res["plain_verdict"])
    
            rag_v = sum(1 for v in res["rag_verdict"].values() if v)
            rag_n = len(res["rag_verdict"])
            plain_v = sum(1 for v in res["plain_verdict"].values() if v)
            plain_n = len(res["plain_verdict"])
    
            rag_header = (
                f"### DrugRAG (LightRAG + Gemma) — {res['rag_latency']:.1f} s\n"
                f"**Verified citations:** {rag_v}/{rag_n} "
                f"<span style='color:#5aae61'>green = in our corpus</span> \u00b7 "
                f"<span style='color:#d6604d'>red = unverifiable</span>\n\n"
            )
            plain_header = (
                f"### Plain Gemma (no retrieval) — {res['plain_latency']:.1f} s\n"
                f"**Verified citations:** {plain_v}/{plain_n} "
                f"<span style='color:#5aae61'>green = in our corpus</span> \u00b7 "
                f"<span style='color:#d6604d'>red = unverifiable</span>\n\n"
            )
            status = f"Total wall time: **{elapsed:.1f} s** (RAG and plain run in parallel)."
            return rag_header + rag_md, plain_header + plain_md, status
        except Exception as e:
            err = f"⚠ Error: `{type(e).__name__}: {e}`"
            return err, err, ""
    
    def run_query_stream(question, mode):
        """Streaming wrapper — yields (rag, plain, status) for live token display."""
        try:
            for update in rag_chat.run_both_stream(question, mode=mode):
                yield update
        except Exception as e:
            err = f"⚠ Error: `{type(e).__name__}: {e}`"
            yield err, err, ""

    with gr.Column():
        gr.Markdown(
            "### Chat — DrugRAG vs plain LLM\n"
            "Same question, two answers: **DrugRAG** retrieves abstracts from "
            "the 6,500-paper corpus and feeds them to Gemma; **plain Gemma** "
            "answers from its training data with no retrieval."
        )
        gr.Markdown(
            "> **About this answer:** Gemma 4 (31 B) via OpenRouter \u00b7 retrieves from "
            "local 6,500-abstract corpus \u00b7 **not** internet-connected \u00b7 LightRAG hybrid.\n"
            "> The first query warms up the embedding model (~15 s); subsequent queries are faster."
        )
        question = gr.Textbox(
            label="Question",
            placeholder="e.g. What is the mechanism of Memantine in angiogenesis?",
            lines=2,
        )
        gr.Examples(examples=EXAMPLES, inputs=question, label="Try one of these")

        # Advanced: retrieval mode (collapsed by default)
        with gr.Accordion("Advanced (for evaluation)", open=False):
            mode_dd = gr.Dropdown(
                choices=["hybrid", "local", "global", "naive"],
                value="hybrid", label="Retrieval mode",
                info="hybrid = balanced (recommended) · local = focuses on the specific drug/gene · global = broad themes across papers · naive = plain keyword, no graph (baseline)",
            )

        run_btn = gr.Button("Run (~30 s, both answers in parallel)", variant="primary")
        status_out = gr.Markdown("")
        with gr.Row():
            rag_out = gr.Markdown("*DrugRAG answer will appear here.*", latex_delimiters=[])
            plain_out = gr.Markdown("*Plain Gemma answer will appear here.*", latex_delimiters=[])
        run_btn.click(fn=run_query, inputs=[question, mode_dd],
                      outputs=[rag_out, plain_out, status_out])
        gr.Markdown(
            "> **Why the citations are trustworthy:** a plain AI can invent "
            "realistic-looking paper IDs. DrugRAG only cites papers it actually "
            "pulled from our library — so every <span style='color:#5aae61;font-weight:600'>green PMID</span> "
            "is a real abstract you can open; <span style='color:#d6604d;font-weight:600'>red</span> means unverified."
        )


