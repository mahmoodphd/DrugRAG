# Glossary
GLOSSARY_MD = """
> **ℹ What these terms mean**
> - **Repurposing score (0–1)** — combined ranking; 40% experimental activity + 35% literature novelty + 25% knowledge-graph support.
> - **Experimental activity** — magnitude of the drug's phenotype change vs. control (HUVEC tube assay).
> - **Effect direction** — anti- or pro-angiogenic (sign of the net activity).
>
> **Reading the literature numbers** — these come from two different places:
> - **From all of PubMed** (the whole database, ~37 million papers — we asked PubMed how many match and stored the count):
>   - **Total PubMed papers** — every paper mentioning the drug, any topic.
>   - **Angiogenesis papers (PubMed)** — the subset that also mention angiogenesis.
> - **From our own 6,500-abstract corpus** (the papers we downloaded; the chat reads only these):
>   - **Papers in our corpus** — how many of the drug's papers are in that local set.
> - **Literature novelty** — higher = less studied in the angiogenesis literature.
>
> Because PubMed's counts cover the whole database, they can be far larger than our 6,500-paper corpus.
>
> - **Literature status** — Well-studied · Some literature · Missed by corpus · Genuinely understudied.
> - **Mechanistic support (KG)** — how strongly the LightRAG knowledge graph links the drug to angiogenesis biology.
> - **Knowledge-graph links** — number of edges connecting the drug to angiogenesis-relevant entities.
"""


